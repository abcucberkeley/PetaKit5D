"""The MATLAB-to-Python mapping table (docs/MATLAB_MAPPING.md), generated from the registry.

Registered functions come with their parameters from their specs; planned ones with the
names the plan gives them and their MATLAB parameters (from the stored inputParser extract)
under the snake_case rule, so names can be reviewed before the ports exist.
"""

from __future__ import annotations

import keyword
from collections.abc import Mapping

from petakit5d.params.check import is_site_value
from petakit5d.params.matlab_source import MatlabFunction
from petakit5d.params.planned import PLANNED
from petakit5d.params.registry import Registry
from petakit5d.params.spec import FunctionSpec, snake_name

HEADER = """\
# MATLAB to Python: functions and parameters

Generated by `python tools/gen_mapping.py` from the parameter registry
(`petakit5d.params`); do not edit it by hand. CI fails when it is out of date.

- **registered**: the port exists; its spec gives the Python function, the MATLAB-name
  function `petakit5d.matlab.<MATLAB name>` and the command line (`pk5d-master <MATLAB name>`).
- **planned**: the name the port will have (PLAN.md section 3.3), for review.
- Parameters keep MATLAB's names in snake_case (`xyPixelSize` -> `xy_pixel_size`,
  `DSRDirName` -> `dsr_dir_name`, `save16bit` -> `save_16bit`); the MATLAB layer takes the
  MATLAB names in any case and unique prefixes, as inputParser does.
"""


def _md(text: str) -> str:
    return str(text).replace("|", "\\|").replace("\n", " ")


def _code(text: str) -> str:
    t = _md(text)
    return f"`{t}`" if t else ""


def _public_name(spec: FunctionSpec) -> str:
    return spec.python_name


def _planned_matches(spec: FunctionSpec, plan: str) -> bool:
    """Same area and function name (the module inside the area may differ)."""
    got = spec.python_name.split(".")
    want = plan.split(".")
    return got[-1] == want[-1] and got[:2] == want[:2]


def name_problems(reg: Registry) -> list[str]:
    """Registered names that differ from the plan."""
    out = []
    plan = {m: p for m, p, _, _ in PLANNED}
    for spec in reg.specs():
        if spec.matlab_name in plan and not _planned_matches(spec, plan[spec.matlab_name]):
            out.append(
                f"{spec.matlab_name}: registered as {spec.python_name}, planned "
                f"{plan[spec.matlab_name]}"
            )
    return out


def generate(reg: Registry, extract: Mapping[str, MatlabFunction]) -> str:
    specs = {s.matlab_name: s for s in reg.specs()}
    unported = reg.not_ported_all()
    plan = {m: (p, t, ph) for m, p, t, ph in PLANNED}
    names = sorted(set(plan) | set(specs), key=str.lower)
    lines = [HEADER]
    n_reg = len(specs)
    n_plan = len([n for n in plan if n not in specs])
    lines.append(f"{n_reg} registered, {n_plan} planned, {len(unported)} not ported.\n")
    lines.append("## Functions\n")
    lines.append("| MATLAB | Python | Status | Task | Phase |")
    lines.append("|---|---|---|---|---|")
    for n in names:
        if n in specs:
            s = specs[n]
            ph = plan.get(n, ("", "", ""))[2]
            note = (
                "" if n not in plan or _planned_matches(s, plan[n][0]) else " (differs from plan)"
            )
            task = s.task or plan.get(n, ("", ""))[1]
            lines.append(f"| `{n}` | `{_public_name(s)}` | registered{note} | {task} | {ph} |")
        else:
            p, t, ph = plan[n]
            lines.append(f"| `{n}` | `{p}` | planned | {t} | {ph} |")
    lines.append("")
    lines.append("## Not ported\n")
    lines.append("| MATLAB | Area | Reason |")
    lines.append("|---|---|---|")
    for n, np_ in unported.items():
        lines.append(f"| `{n}` | {np_.area} | {_md(np_.reason)} |")
    lines.append("")
    lines.append("## Parameters\n")
    lines.append(
        "Kind: req (required, positional), opt (optional, positional), par (name-value; "
        "keyword-only in Python), pos (positional; MATLAB fills defaults by nargin). Defaults "
        "in MATLAB syntax. Registered functions show their spec; planned ones MATLAB's "
        "inputParser or arguments block under the naming rule.\n"
    )
    for n in names:
        if n in specs:
            lines.extend(_spec_section(specs[n]))
        elif n in extract:
            lines.extend(_planned_section(n, plan[n][0], extract[n]))
        else:
            lines.append(f"### `{n}` -> `{plan[n][0]}` (planned)\n")
            lines.append("No inputParser block in MATLAB (positional arguments only).\n")
    lines.extend(_keyword_section(extract, names))
    return "\n".join(lines).rstrip() + "\n"


def _spec_section(s: FunctionSpec) -> list[str]:
    out = [f"### `{s.matlab_name}` -> `{s.python_name}`\n"]
    if s.doc:
        out.append(_md(s.doc) + "\n")
    out.append("| MATLAB | Python | Kind | Default | Validator | Meaning |")
    out.append("|---|---|---|---|---|---|")
    kinds = {"required": "req", "optional": "opt", "parameter": "par", "positional": "pos"}
    for p in s.params:
        notes = []
        if p.python_only:
            notes.append("Python only")
        if p.differs:
            notes.append(f"default differs from MATLAB: {p.differs}")
        if p.py != snake_name(p.matlab):
            notes.append("renamed")
        meaning = _md(p.doc) + (f" ({'; '.join(notes)})" if notes else "")
        default = "" if p.required else _code(p.default_text())
        out.append(
            f"| `{p.matlab}` | `{p.py}` | {kinds[p.kind]} | {default} | "
            f"{_code(p.validator or '')} | {meaning} |"
        )
    out.append("")
    return out


def _planned_section(name: str, py: str, fn: MatlabFunction) -> list[str]:
    out = [f"### `{name}` -> `{py}` (planned)\n"]
    out.append("| MATLAB | Python | Kind | Default | Validator |")
    out.append("|---|---|---|---|---|")
    kinds = {"required": "req", "optional": "opt", "parameter": "par", "positional": "pos"}
    for p in fn.params:
        default = "<site-specific>" if is_site_value(p.default) else p.default or ""
        validator = "<site-specific>" if is_site_value(p.validator) else p.validator or ""
        out.append(
            f"| `{p.name}` | `{snake_name(p.name)}` | {kinds[p.kind]} | "
            f"{_code(default) if p.kind != 'required' else ''} | {_code(validator)} |"
        )
    out.append("")
    return out


def _keyword_section(extract: Mapping[str, MatlabFunction], names: list[str]) -> list[str]:
    """Parameter names whose snake_case form needs an override (keywords, clashes)."""
    rows = []
    for n in names:
        fn = extract.get(n)
        if fn is None:
            continue
        seen: dict[str, str] = {}
        for p in fn.params:
            py = snake_name(p.name)
            if keyword.iskeyword(py):
                rows.append(f"| `{n}` | `{p.name}` | `{py}` is a Python keyword: use `{py}_` |")
            elif py in seen:
                rows.append(f"| `{n}` | `{p.name}` | same snake_case name as `{seen[py]}` |")
            seen.setdefault(py, p.name)
    if not rows:
        return []
    return [
        "## Parameter names that need an override\n",
        "| Function | MATLAB | Why |",
        "|---|---|---|",
        *rows,
        "",
    ]
