        function teardown(fixture)
            setenv('PATH', fixture.OriginalPath);
            if exist(fixture.Folder, 'dir')
                rmdir(fixture.Folder, 's');
            end
        end

        function setJobStates(fixture, jobId, states, outputs)
            % jobId as squeue shows it, e.g., '123_7' for task 7 of job 123.
            % outputs (optional): files the job writes (empty) when squeue
            % first reports it running, e.g., the result of its first task,
            % or all its results while it is still exiting
            fid = fopen(sprintf('%s/state/%s', fixture.Folder, jobId), 'w');
            fprintf(fid, '%s\n', states{:});
            fclose(fid);
            if nargin > 3
                fid = fopen(sprintf('%s/state/%s.outputs', fixture.Folder, jobId), 'w');
                fprintf(fid, '%s\n', outputs{:});
                fclose(fid);
            end
        end

        function clearCalls(fixture)
            % forget the calls so far (their logs) and number the next jobs
            % from 1000 again; the states set stay
            delete(fullfile(fixture.Folder, '*.log'));
            nextFn = fullfile(fixture.Folder, 'next_id');
            if isfile(nextFn)
                delete(nextFn);
            end
        end

        function rejectSubmissions(fixture, n, message)
            % the next n sbatch calls fail without submitting a job, as
            % when the user's job submit limit is reached; message: what
            % sbatch prints instead, e.g., 'sbatch: error: Batch job
            % submission failed: Socket timed out on send/recv operation'
            % (an answer lost on its way: the framework then looks for the
            % job)
            if nargin < 3
                message = ['sbatch: error: Batch job submission failed: Job violates accounting/QOS ', ...
                    'policy (job submit limit, user''s size and/or time limits)'];
            end
            fid = fopen([fixture.Folder, '/reject_msg'], 'w');
            fprintf(fid, '%s\n', message);
            fclose(fid);
            fid = fopen([fixture.Folder, '/reject'], 'w');
            fprintf(fid, '%d\n', n);
            fclose(fid);
        end

        function loseSubmissionAnswers(fixture, n)
            % the next n sbatch calls submit their jobs (with the next ids)
            % but fail with "Socket timed out on send/recv operation", as
            % when the controller made the job and its answer was lost
            fid = fopen([fixture.Folder, '/lose'], 'w');
            fprintf(fid, '%d\n', n);
            fclose(fid);
        end

        function failQueries(fixture, n, message)
            % the next n squeue calls fail (exit status 1) without using a
            % job's state, as when the controller is busy; message: what
            % squeue prints
            if nargin < 3
                message = 'slurm_load_jobs error: Socket timed out on send/recv operation';
            end
            fid = fopen([fixture.Folder, '/squeue_fail_msg'], 'w');
            fprintf(fid, '%s\n', message);
            fclose(fid);
            fid = fopen([fixture.Folder, '/squeue_fail'], 'w');
            fprintf(fid, '%d\n', n);
            fclose(fid);
        end

        function setNodes(fixture, varargin)
            % the nodes scontrol show node -o reports, one line each (see
            % nodeLine); with several sets of lines, each call reports the
            % next set, and the last one stays
            old = [dir([fixture.Folder, '/nodes_*'])];
            for i = 1 : numel(old)
                delete([fixture.Folder, '/', old(i).name]);
            end
            for i = 1 : numel(varargin)
                fid = fopen(sprintf('%s/nodes_%d', fixture.Folder, i), 'w');
                fprintf(fid, '%s\n', varargin{i}{:});
                fclose(fid);
            end
        end

        function setTestOnly(fixture, partition, answer)
            % what sbatch --test-only answers for jobs of partition: 'now'
            % (the default), 'later' (2099) or 'error' (the job is refused)
            fid = fopen(sprintf('%s/testonly/%s', fixture.Folder, partition), 'w');
            fprintf(fid, '%s\n', answer);
            fclose(fid);
        end

        function setJobAttributes(fixture, jobId, partition, cpus, memMB, gpus, qos)
            % a job's resources as squeue -O lists them (sbatch records its
            % own jobs'), e.g. for jobs a test puts into the queue itself
            if nargin < 6
                gpus = 0;
            end
            if nargin < 7
                qos = 'normal';
            end
            fid = fopen(sprintf('%s/jobs/%s', fixture.Folder, jobId), 'w');
            fprintf(fid, 'partition=%s qos=%s cpus=%d mem=%d gpus=%d\n', partition, qos, cpus, memMB, gpus);
            fclose(fid);
        end

        function [attrs] = jobAttributes(fixture, jobId)
            % a job's partition, qos, cpus, mem (MB) and gpus as recorded
            attrs = struct();
            fn = sprintf('%s/jobs/%s', fixture.Folder, jobId);
            if ~isfile(fn)
                return;
            end
            for kv = strsplit(strip(fileread(fn)))
                p = strsplit(kv{1}, '=');
                v = str2double(p{2});
                if isnan(v)
                    v = p{2};
                end
                attrs.(p{1}) = v;
            end
        end

        function failUpdates(fixture)
            % from now on scontrol update fails (as for a QOS the job's new
            % partition doesn't allow)
            fclose(fopen([fixture.Folder, '/update_fail'], 'w'));
        end

        function makeLogFiles(fixture)
            % from now on sbatch makes the files of its -o and -e options
            % (with %A, %a and %j filled in), as Slurm does when a job
            % starts; only files in the temporary folder (of the fixture
            % and the tests' folders; also as its path with symbolic links
            % resolved, as /private/var on a Mac), so that no test writes
            % elsewhere
            fclose(fopen([fixture.Folder, '/make_logs'], 'w'));
        end

        function [n] = callCount(fixture, cmd)
            fn = sprintf('%s/%s.log', fixture.Folder, cmd);
            n = 0;
            if exist(fn, 'file')
                n = numel(splitlines(strip(fileread(fn))));
            end
        end

        function [args] = calls(fixture, cmd)
            % the arguments of every call, one cell per call
            fn = sprintf('%s/%s.log', fixture.Folder, cmd);
            args = {};
            if exist(fn, 'file')
                args = splitlines(strip(fileread(fn)));
            end
        end

        function [cmds] = history(fixture)
            % every call of all commands in call order, as 'command arguments'
            fn = [fixture.Folder, '/history.log'];
            cmds = {};
            if exist(fn, 'file')
                cmds = splitlines(strip(fileread(fn)));
            end
        end
    end

    methods (Static)
        function [line] = nodeLine(name, partitions, cpus, cpuAlloc, memMB, allocMB, gpus, gpuAlloc, state, features)
            % a node as scontrol show node -o shows it
            if nargin < 7
                gpus = 0;
            end
            if nargin < 8
                gpuAlloc = 0;
            end
            if nargin < 9
                state = 'MIXED';
            end
            if nargin < 10
                features = '(null)';
            end
            cfg = sprintf('cpu=%d,mem=%dM,billing=%d', cpus, memMB, cpus);
            alloc = sprintf('cpu=%d,mem=%dM', cpuAlloc, allocMB);
            gres = '(null)';
            if gpus > 0
                cfg = sprintf('%s,gres/gpu=%d', cfg, gpus);
                gres = sprintf('gpu:%d', gpus);
            end
            if gpuAlloc > 0
                alloc = sprintf('%s,gres/gpu=%d', alloc, gpuAlloc);
            end
            line = sprintf(['NodeName=%s Arch=x86_64 CoresPerSocket=%d CPUAlloc=%d CPUEfctv=%d CPUTot=%d ', ...
                'AvailableFeatures=%s ActiveFeatures=%s Gres=%s OS=Linux 4.18.0 #1 SMP RealMemory=%d ', ...
                'AllocMem=%d State=%s Partitions=%s CfgTRES=%s AllocTRES=%s'], name, cpus, cpuAlloc, ...
                cpus, cpus, features, features, gres, memMB, allocMB, state, partitions, cfg, alloc);
        end
    end

    methods (Access = protected)
        function [tf] = isCompatible(~, ~)
            % each test gets its own fake Slurm
            tf = false;
        end
    end

    methods (Access = private)
        function writeStub(fixture, cmd, body)
            fn = sprintf('%s/%s', fixture.Folder, cmd);
            fid = fopen(fn, 'w');
            fprintf(fid, '#!/bin/sh\nD="$(dirname "$0")"\necho "$*" >> "$D/%s.log"\necho "%s $*" >> "$D/history.log"\n', cmd, cmd);
            fprintf(fid, '%s\n', body{:});
            fclose(fid);
            fileattrib(fn, '+x');
        end
    end
