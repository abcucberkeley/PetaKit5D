    % prints a new job id (1000, 1001, ...), squeue lists the jobs whose
    % states a test set with setJobStates, and scancel does nothing. Every
    % call is logged, so tests can count them, and history lists all calls
    % in order. Not available on Windows.
    %
    % A job's states are used one per squeue call that names it (-j), and
    % the last one stays: setJobStates('123_7', {'PD', 'PD', 'R'}) reports
    % the job pending twice and then running. The state 'done' means the
    % job is gone. A pending job's reason (squeue -o %r) is Resources, or
    % the one after a colon ('PD:None': not looked at by the scheduler
    % yet). squeue without -j lists all jobs in their current state (it
    % uses no state), with -t and -o (%i, %T, %t, %r, %k: the comment
    % sbatch got) and -h. The jobs run nothing, but a job can write (empty)
    % output files when it is first reported running. Failures:
    % rejectSubmissions makes sbatch fail (a refusal by default),
    % loseSubmissionAnswers makes it fail after it made the job, and
    % failQueries makes squeue fail.
    %
    % For jobs on several partitions (slurm_alternatives): sbatch records
    % each job's partition, QOS, CPUs, memory and GPUs, which squeue --me
    % -O (JobArrayID, Partition, QOS, NumCPUs, tres-alloc, Reason; with -t
    % and -p) lists, and scontrol update changes while the job is pending
    % (else it fails, as for a job that started); scontrol show node gives
    % the nodes a test set with setNodes (none by default), sbatch
    % --test-only answers per partition as setTestOnly says (start now by
    % default; it takes no job id), and other scontrol commands run the real
    % scontrol if there is one.

    properties (SetAccess = private)
        Folder
    end

    properties (Access = private)
